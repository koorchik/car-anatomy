// Finds a per-engine output trim so all engines sit at one level at high rpm, full throttle.
// Rewrites src/audio/loudness-trim.ts: `node scripts/calibrate.ts`.

import { writeFileSync } from 'node:fs';
import { ENGINES } from '../src/data/engines.ts';
import { render, rmsDb } from './render-audio.ts';

const TARGET_DB = -13;
// Averaged over the rev range, so one exhaust resonance doesn't set the level of the whole engine.
const POINTS = [
  [0.35, 0.45],
  [0.55, 0.7],
  [0.8, 1],
  [0.95, 1],
] as const;

const lines: string[] = [];
for (const spec of ENGINES) {
  let trim = 0.5;
  for (let pass = 0; pass < 4; pass++) {
    const levels = POINTS.map(([share, pedal]) => {
      const rpm = spec.redlineRpm * share;
      const { l, r } = render(spec.id, [{ seconds: 0.4, pedal, rpm }, { seconds: 0.8, pedal, rpm }], trim);
      return (rmsDb(l, 19200) + rmsDb(r, 19200)) / 2;
    });
    const level = levels.reduce((a, b) => a + b, 0) / levels.length;
    trim *= Math.pow(10, (TARGET_DB - level) / 20);
  }
  trim = Math.min(2.5, Math.max(0.1, trim));
  lines.push(`  '${spec.id}': ${trim.toFixed(3)},`);
}
const out = `// Generated by scripts/calibrate.ts.\nexport const LOUDNESS_TRIM: Record<string, number> = {\n${lines.join('\n')}\n};\n`;
writeFileSync('src/audio/loudness-trim.ts', out);
console.log(out);
