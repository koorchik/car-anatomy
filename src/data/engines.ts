export const ENGINES: EngineSpec[] = CATALOGUE.map((entry) => catalogueSpec(entry));

const variantCache = new Map<string, EngineSpec>();

/** A page's own engine, or one of its variants as `page/variant`. */
export const engineById = (id: string): EngineSpec | undefined => {
  const [page, variantId] = id.split('/');
  if (!variantId) return ENGINES.find((e) => e.id === page);
  const cached = variantCache.get(id);
  if (cached) return cached;
  const entry = CATALOGUE.find((e) => e.id === page);
  const variant = ENGINE_VARIANTS[page!]?.variants.find((v) => v.id === variantId);
  if (!entry || !variant) return undefined;
  const spec = catalogueSpec(entry, variant);
  variantCache.set(id, spec);
  return spec;
};

/** All engines of a page in list order, the page's own first. */
export const pageChoices = (id: string): Array<{ id: string; name: string }> => {
  const page = id.split('/')[0]!;
  const entry = CATALOGUE.find((e) => e.id === page);
  if (!entry) return [];
  const known = ENGINE_VARIANTS[page];
  return [{ id: page, name: known?.base.name ?? entry.example }, ...(known?.variants ?? []).map((v) => ({ id: `${page}/${v.id}`, name: v.name }))];
};

/** Facts about one engine for the article, where researched. */
export const engineFacts = (id: string): EngineFacts | undefined => {
  const [page, variantId] = id.split('/');
  const known = ENGINE_VARIANTS[page!];
  return variantId ? known?.variants.find((v) => v.id === variantId) : known?.base;
};
